import type { Request, Response, NextFunction } from 'express';
import { z, ZodSchema } from 'zod';

// check registerSchema to see how it works

// check the data before reaching the route handler
// eg if the email is not a valid email address, return a 400 error

export const validateBody = (schema: ZodSchema) => {
  return (req: Request, res: Response, next: NextFunction) => {
    try {
      req.body = schema.parse(req.body); // transform the request body into the shape of the schema
      next();
    } catch (error) {
      if (error instanceof z.ZodError) {
        return res.status(400).json({
          error: 'Validation failed',
          details: error.errors.map(err => ({
            field: err.path.join('.'),
            message: err.message
          }))
        });
      }
      next(error);
    }
  };
};

